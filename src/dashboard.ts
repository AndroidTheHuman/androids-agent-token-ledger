// `npm run ledger -- dashboard` (brief 001 part D): writes dashboard/data.js from the committed JSON, so
// dashboard/index.html can be opened from disk with no server and no network. The page reads only what this
// file puts on `TOKEN_LEDGER`; no number is computed from anything else.
// Runs under plain Node (type stripping), so it uses erasable TypeScript only.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PCT_OF_SOURCE } from './format.ts';

/** Where each key of `TOKEN_LEDGER` comes from, relative to the data directory (or `docs/` for `own`). */
export const SOURCES = {
  summary: ['data', 'corpus/summary.json'],
  sessions: ['data', 'corpus/sessions.json'],
  game: ['data', 'corpus/game-ledger.json'],
  rules: ['data', 'rules.json'],
  own: ['docs', 'session-ledger.json'],
} as const;

export type LedgerKey = keyof typeof SOURCES;

const HEADER = `// Generated by \`npm run ledger -- dashboard\` from data/corpus/*.json, data/rules.json and docs/session-ledger.json;
// do not edit by hand. Numbers, ids, timestamps, codes, tool names and labels only (D2).
// summary: summary.json; sessions: sessions.json; game: game-ledger.json; rules: rules.json; own: this project's ledger.
`;

/** The text of dashboard/data.js: one key per line, then the shared share formatter (src/format.ts). */
export function buildDataJs(dataDir: string, docsDir: string): string {
  const lines = (Object.keys(SOURCES) as LedgerKey[]).map((key) => {
    const [base, file] = SOURCES[key];
    const value: unknown = JSON.parse(readFileSync(join(base === 'data' ? dataDir : docsDir, file), 'utf8'));
    return `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`;
  });
  return `${HEADER}globalThis.TOKEN_LEDGER = {\n${lines.join(',\n')},\n};\n\n// The one share formatter, shared with METRICS.md (src/format.ts).\n${PCT_OF_SOURCE}\n`;
}

export function runDashboard(dataDir: string, docsDir: string, dashboardDir: string): { path: string; bytes: number } {
  mkdirSync(dashboardDir, { recursive: true });
  const text = buildDataJs(dataDir, docsDir);
  const path = join(dashboardDir, 'data.js');
  writeFileSync(path, text);
  return { path, bytes: Buffer.byteLength(text) };
}
